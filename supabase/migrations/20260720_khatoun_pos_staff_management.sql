create table if not exists public.staff_members (
  id uuid primary key default gen_random_uuid(),
  employee_number bigint generated by default as identity unique,
  profile_id uuid unique references public.profiles(id) on delete set null,
  full_name text not null check (length(btrim(full_name)) > 0),
  phone text,
  secondary_phone text,
  job_title text not null check (length(btrim(job_title)) > 0),
  department text not null check (department in ('service', 'cashier', 'kitchen', 'management', 'cleaning', 'barista', 'shisha', 'other')),
  employment_type text not null default 'full_time' check (employment_type in ('full_time', 'part_time', 'temporary')),
  shift_type text not null default 'fixed' check (shift_type in ('morning', 'evening', 'night', 'rotating', 'fixed')),
  hire_date date,
  birth_date date,
  salary numeric(12,0) check (salary is null or salary >= 0),
  address text,
  emergency_contact_name text,
  emergency_contact_phone text,
  notes text,
  status text not null default 'active' check (status in ('active', 'on_leave', 'inactive', 'terminated')),
  has_system_access boolean not null default false,
  created_by uuid references public.profiles(id),
  updated_by uuid references public.profiles(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists staff_members_status_idx on public.staff_members(status);
create index if not exists staff_members_department_idx on public.staff_members(department);
create index if not exists staff_members_profile_id_idx on public.staff_members(profile_id);

drop trigger if exists set_staff_members_updated_at on public.staff_members;
create trigger set_staff_members_updated_at before update on public.staff_members
  for each row execute function public.set_updated_at();

